"""Generate linker forwarders that turn our DLL into a transparent winmm.dll proxy.

Every export of the real System32 winmm.dll is forwarded to it through the
GLOBALROOT path, so the loader resolves the genuine DLL by absolute path and
never recurses into our own module. Original ordinals are preserved, because
some importers bind by ordinal.

usage: python gen_winmm_exports.py <dumpbin /exports output> <out .inc>
"""
import re
import sys

TARGET = r"\\.\GLOBALROOT\SystemRoot\System32\winmm.dll"
ROW = re.compile(r"^\s+(\d+)\s+(?:[0-9A-F]+\s+)?[0-9A-F]{8}\s+(\S+)")


def c_escape(s: str) -> str:
    return s.replace("\\", "\\\\")


def main(src: str, dst: str) -> None:
    exports = []
    for line in open(src, encoding="utf-8", errors="replace"):
        m = ROW.match(line)
        if m:
            exports.append((int(m.group(1)), m.group(2)))
    if len(exports) < 150:
        raise SystemExit(f"only {len(exports)} exports parsed; dumpbin output looks wrong")

    out = [
        "// GENERATED by tools/gen_winmm_exports.py from System32\\winmm.dll - do not edit.",
        f"// {len(exports)} exports forwarded to {TARGET}",
        "#pragma once",
    ]
    for ordinal, name in sorted(exports):
        if name == "[NONAME]":
            sym = f"__winmm_ord{ordinal}"
            out.append(f'#pragma comment(linker, "/export:{sym}={c_escape(TARGET)}.#{ordinal},@{ordinal},NONAME")')
        else:
            out.append(f'#pragma comment(linker, "/export:{name}={c_escape(TARGET)}.{name},@{ordinal}")')
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {len(exports)} forwarders to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
