"""Generate srcScripts/cts4p/sync/command_table.py from the decompiled game scripts.

Lists every top-level function decorated with sims4.commands.Command(...,
command_type=...Live...) whose name starts with one of FORWARDED_PREFIXES.
On a guest these commands are sent to the host and executed there on behalf
of the guest's virtual client, so the guest controls its own Sim while the
host's simulation stays the single source of truth.

usage: python tools/gen_command_table.py <_decompiled_ref/simulation> <out .py>
"""
import os
import re
import sys

# Commands the player's UI sends during live mode that change or query simulation state.
FORWARDED_PREFIXES = (
    "interactions.", "clock.", "sims.", "ui.dialog.", "careers.", "travel.", "household.",
    "households.", "cas.", "situations.", "phone.", "relationships.", "inventory.", "crafting.",
    "outfits.", "aspirations.", "drama.", "lighting.", "objects.", "venues.", "clubs.", "business.",
    "restaurant.", "retail.", "holiday.", "seasons.", "weather.", "university.", "lifestyles.",
    "familiars.", "bills.", "rewards.", "rabbit_hole.", "zone_modifier.", "live_drag.", "lot_decorations.",
    "story_progression.", "pregnancy.", "ui.picker", "ui.travel", "ui.sim_skewer", "ui.dialog",
)
# Never forwarded even if they match: local UI/camera/debug/save concerns.
LOCAL_ONLY = (
    "sims.exit2cas", "clock.build_buy_pause_unpause", "sims.get_travel_menu_info",
)

DECORATOR = re.compile(r"^@(?:sims4\.commands\.)?Command\((.*?)\)\s*$", re.S)
ALIAS = re.compile(r'"([A-Za-z0-9_.]+)"')
DEF = re.compile(r"^def ([A-Za-z_][A-Za-z0-9_]*)\(")


OPTION_PATTERNS = {
    # keyword -> regex capturing the enum member names used in the original decorator
    "command_restrictions": re.compile(r"command_restrictions=\(?((?:CommandRestrictionFlags\.\w+\s*\|?\s*)+)"),
    "pack": re.compile(r"pack=\(?(?:sims4\.common\.)?Pack\.(\w+)"),
    "console_type": re.compile(r"console_type=\(?(?:sims4\.commands\.)?CommandType\.(\w+)"),
}


def decorator_options(text):
    """Keyword arguments of the original Command(...) besides command_type, as enum member names."""
    opts = {}
    m = OPTION_PATTERNS["command_restrictions"].search(text)
    if m:
        opts["command_restrictions"] = tuple(re.findall(r"CommandRestrictionFlags\.(\w+)", m.group(1)))
    for key in ("pack", "console_type"):
        m = OPTION_PATTERNS[key].search(text)
        if m:
            opts[key] = m.group(1)
    return opts


def scan_file(path, module):
    lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
    found = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("@sims4.commands.Command(") or line.startswith("@Command("):
            # Collect the (possibly multi-line) decorator until parentheses balance.
            text, depth, j = "", 0, i
            while j < len(lines):
                text += lines[j] + "\n"
                depth += lines[j].count("(") - lines[j].count(")")
                if depth <= 0:
                    break
                j += 1
            k = j + 1
            while k < len(lines) and lines[k].startswith("@"):
                k += 1
            m = DEF.match(lines[k]) if k < len(lines) else None
            if m and "CommandType.Live" in text and "console_type" not in text.split("command_type")[0]:
                head = text.split("command_type")[0]
                aliases = tuple(ALIAS.findall(head))
                if aliases:
                    found.append((module, m.group(1), aliases, decorator_options(text)))
            i = k
        i += 1
    return found


def main(root, out):
    entries = []
    for dirpath, _, files in os.walk(root):
        for name in files:
            if not name.endswith(".py") or name.startswith("_decompile"):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, root)[:-3].replace(os.sep, ".")
            if rel.endswith(".__init__"):
                rel = rel[: -len(".__init__")]
            entries.extend(scan_file(path, rel))
    keep = []
    for module, func, aliases, opts in entries:
        names = tuple(a for a in aliases if a.startswith(FORWARDED_PREFIXES) and a not in LOCAL_ONLY)
        if names:
            keep.append((module, func, names, opts))
    keep.sort(key=lambda e: (e[0], e[1]))
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""GENERATED by tools/gen_command_table.py from the decompiled game scripts - do not edit.\n\n')
        fh.write("Live commands a guest forwards to the host: (module, function, command names, options).\n")
        fh.write("options = the original decorator's command_restrictions / pack / console_type, re-applied when\n")
        fh.write("the forwarder is registered so the base game's rules are preserved.\n")
        fh.write('Functions missing in a given game version are skipped at runtime."""\n\n')
        fh.write("FORWARDED_COMMANDS = (\n")
        for module, func, names, opts in keep:
            fh.write("    ({!r}, {!r}, {!r}, {!r}),\n".format(module, func, names, opts))
        fh.write(")\n")
    print("{} live commands scanned, {} forwarded -> {}".format(len(entries), len(keep), out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
